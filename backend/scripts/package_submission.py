"""Regenerate submission artifacts from a full, common-simulator demo run.

From repository root: PYTHONPATH=backend python backend/scripts/package_submission.py
"""
from __future__ import annotations
import copy
import hashlib
import json
import platform
from pathlib import Path
import subprocess
from importlib.metadata import version
from app.core.runner import load_scenario, run_day

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'submission' / 'demo-run'


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    scenario = load_scenario()
    scenario_path = OUT / 'scenario.json'
    scenario_path.write_text(json.dumps(scenario, indent=2) + '\n')
    rows = {}
    evidence = {}
    for mode in ('ours', 'baseline'):
        log_path = OUT / f'event_log_{mode}.jsonl'
        world = run_day(copy.deepcopy(scenario), mode, dt=1.0, log_path=log_path)
        metrics = world.run_metrics().model_dump()
        if not world.ended or metrics['violations']:
            raise RuntimeError(f'{mode}: incomplete run or executed violation')
        records = [json.loads(line) for line in log_path.read_text().splitlines()]
        if not any(e.get('kind') == 'event' and e.get('type') == 'breakdown' for e in records):
            raise RuntimeError('Demo must include the scripted breakdown')
        if any(u[1] > u[0]+1e-6 for j in world.jobs.values() for u in j.units):
            raise RuntimeError('Duplicated work')
        rows[mode] = metrics
        evidence[mode] = {'log': log_path.name, 'records': len(records),
                          'sha256': hashlib.sha256(log_path.read_bytes()).hexdigest()}
    source = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
    result = {'source_commit': source, 'scenario': 'scenario.json',
              'scenario_sha256': hashlib.sha256(scenario_path.read_bytes()).hexdigest(),
              'simulator': 'Python MockGateway (not AgOpenWeb)', 'tick_min': 1.0,
              'python': platform.python_version(),
              'dependencies': {name: version(name) for name in ('fastapi', 'pydantic', 'uvicorn')},
              'policies': {'ours': 'multi-order greedy insertion + bounded move/swap search',
                           'baseline': 'FCFS: submission order, first feasible compatible tractor'},
              'llm_used_in_comparison': False,
              'scope': 'One full-day scenario; same simulator, configuration and scripted events. No manually injected events. Timing is machine-dependent.',
              'metrics': rows, 'evidence': evidence}
    (OUT / 'results.json').write_text(json.dumps(result, indent=2) + '\n')
    keys = [('completed', 'Completed jobs'), ('on_time', 'On-time jobs'),
            ('travel_min', 'Travel (tractor-min)'), ('idle_min', 'Idle (tractor-min)'),
            ('productive_min', 'Productive work (min)'), ('violations', 'Reported executed violations')]
    table = '\n'.join(f"| {label} | {rows['ours'][key]} | {rows['baseline'][key]} |" for key, label in keys)
    improvement = lambda key: round(100*(rows['baseline'][key]-rows['ours'][key])/rows['baseline'][key], 1) if rows['baseline'][key] else 0
    (ROOT / 'submission' / 'RESULTS.md').write_text(f'''# Demo run and baseline comparison

Generated by `backend/scripts/package_submission.py` from source commit `{source}`.

| Metric | Our coordinator | FCFS baseline |
|---|---:|---:|
{table}

On this scenario, travel is reduced by **{improvement('travel_min')}%** and idle time by **{improvement('idle_min')}%**. Completion counts are shown alongside efficiency; this is not a claim that our heuristic always beats FCFS.

## Reproduce

From the repository root, with backend requirements installed:

```bash
PYTHONPATH=backend python backend/scripts/package_submission.py
```

PowerShell: `$env:PYTHONPATH="backend"`, then `python backend/scripts/package_submission.py`.

## Run contents and assumptions

- `demo-run/scenario.json`: exact configuration, including three tractors, eight fields, 12 jobs and Tractor 1's breakdown at farm minute 50 (6:50 AM).
- `demo-run/event_log_ours.jsonl`: actual coordinator execution log from this headless demonstration.
- `demo-run/event_log_baseline.jsonl`: actual FCFS log through the same simulator and events.
- `demo-run/results.json`: measured metrics, environment and SHA-256 evidence hashes.
- The demo runs a six AM–six PM simulated day with a one-minute maximum tick; the event engine stops at event/decision times.
- This is the scored **FastAPI/Python brain/MockGateway** path, not the separate AgOpenWeb bridge. Positions and rates are illustrative. Field work occurs at field entrances and progress is tracked in work units.
- No LLM was used in these benchmark runs. The optional AI Supervisor is a separate review layer; its suggestions are not credited with these results.
- Travel and idle are aggregated tractor-minutes, not wall-clock demo duration. Replan runtime depends on machine load and the bounded search.
- Both policies obey the same compatibility, deadlines, route and fuel rules. This evidence covers one scenario; it does not prove general optimality or real-world safety.
- These are regenerated headless demo logs, not a claim of a recorded browser or on-stage session. If the final presentation injects extra manual events, export that session's `/api/log` separately and recompute its matching baseline.
''')
    print(json.dumps(rows, indent=2))


if __name__ == '__main__':
    main()
